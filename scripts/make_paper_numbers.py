"""Write paper/numbers.tex: every E1-E2 number the paper/report quotes, as LaTeX macros, straight from results/.

Rule (PLANNING.md): numbers are never retyped. Cite \\taxClMal etc. instead of typing 8.9.
Macro names: \\tax<Tok><Lang>, \\fert<Tok><Lang>, \\sb<Tok><Lang> (single-byte %), \\inr<Tok><Lang>, plus summaries.
"""
import os

import pandas as pd

from tokentax.langs import AUDIT_LANGS, ENGLISH, LANG_NAMES
from tokentax.metrics import summarize_e1

TOK = {"cl100k": "Cl", "o200k": "Oo", "llama3": "Ll", "qwen2.5": "Qw", "gemma2": "Ge", "xlmr": "Xl", "sarvam1": "Sa"}
LANG = {"eng_Latn": "Eng", "hin_Deva": "Hin", "mar_Deva": "Mar", "ben_Beng": "Ben", "asm_Beng": "Asm",
        "guj_Gujr": "Guj", "pan_Guru": "Pan", "ory_Orya": "Ori", "urd_Arab": "Urd", "tam_Taml": "Tam",
        "tel_Telu": "Tel", "kan_Knda": "Kan", "mal_Mlym": "Mal"}

s = summarize_e1(pd.read_csv("results/e1_intrinsic.csv"))
eng_fert = s[s.lang == ENGLISH].set_index("tokenizer").fertility
s["fert_ratio"] = s.fertility / s.tokenizer.map(eng_fert)
cost = pd.read_csv("results/e2_cost.csv").set_index(["tokenizer", "lang"])

lines = ["% AUTO-GENERATED by scripts/make_paper_numbers.py -- do not edit by hand"]


def mac(name, val):
    lines.append(f"\\newcommand{{\\{name}}}{{{val}}}")


for _, r in s.iterrows():
    t, l = TOK[r.tokenizer], LANG[r.lang]
    mac(f"tax{t}{l}", f"{r.tax_vs_eng:.1f}")
    mac(f"fert{t}{l}", f"{r.fertility:.2f}")
    mac(f"fertratio{t}{l}", f"{r.fert_ratio:.1f}")
    mac(f"sb{t}{l}", f"{r.pct_single_byte:.0f}")
    inr = cost.loc[(r.tokenizer, r.lang), "inr_per_1k_eng_words"]
    if pd.notna(inr):
        mac(f"inr{t}{l}", f"{inr:.2f}")

indic = s[s.lang != ENGLISH]
for tok, g in indic.groupby("tokenizer"):
    t = TOK[tok]
    mac(f"meanTax{t}", f"{g.tax_vs_eng.mean():.1f}")
    hi = g.loc[g.tax_vs_eng.idxmax()]
    mac(f"maxTax{t}", f"{hi.tax_vs_eng:.1f}")
    mac(f"maxTaxLang{t}", LANG_NAMES[hi.lang])
    # usable 128k window in English-equivalent tokens at the mean tax, in thousands
    mac(f"kWin{t}", f"{128 / g.tax_vs_eng.mean():.0f}k")
cl, oo = indic[indic.tokenizer == "cl100k"].tax_vs_eng.mean(), indic[indic.tokenizer == "o200k"].tax_vs_eng.mean()
mac("taxCutClToOoPct", f"{100 * (1 - (oo - 1) / (cl - 1)):.0f}")  # reduction of the EXCESS tax
mac("nTokenizers", str(s.tokenizer.nunique()))
mac("nLangs", str(len([l for l in AUDIT_LANGS if l in set(s.lang)]) - 1))

os.makedirs("paper", exist_ok=True)
open("paper/numbers.tex", "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(f"wrote paper/numbers.tex ({len(lines) - 1} macros)")
